// ─── Derived collections ───────────────────────────────────────────────────────
export const featuredCars = cars.filter((c) => c.isFeatured);
export const popularCars = cars.filter((c) => c.isPopular);
export const availableCars = cars.filter((c) => c.available);

export function getCarBySlug(slug: string): Car | undefined {
  return cars.find((c) => c.slug === slug);
}

export function getCarById(id: string): Car | undefined {
  return cars.find((c) => c.id === id);
}

export function getRelatedCars(car: Car, limit = 3): Car[] {
  return cars
    .filter((c) => c.id !== car.id && c.category === car.category)
    .slice(0, limit);
}
